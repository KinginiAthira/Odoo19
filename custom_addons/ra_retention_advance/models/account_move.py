from collections import defaultdict

from odoo import Command, _, api, fields, models
from odoo.exceptions import UserError, ValidationError

RA_TYPES = [
    ('transfer', 'Retention Held'),
    ('release', 'Retention Released'),
    ('return', 'Retention Returned (Credit Note)'),
    ('advance_apply', 'Advance Recovered'),
    ('advance_return', 'Advance Returned (Credit Note)'),
]


class AccountMove(models.Model):
    _inherit = 'account.move'

    # ------------------------------------------------------------------
    # Inputs on the customer invoice
    # ------------------------------------------------------------------
    retention_percent = fields.Float(string='Retention %', digits=(5, 2), default=0.0)
    retention_due_date = fields.Date(string='Expected Handover Date')
    advance_payment_id = fields.Many2one(
        'account.payment', string='Advance Payment', copy=False,
        domain="[('payment_type', '=', 'inbound'), ('partner_type', '=', 'customer'),"
               " ('partner_id', 'child_of', commercial_partner_id),"
               " ('state', 'in', ('in_process', 'paid')), ('is_reconciled', '=', False),"
               " ('company_id', '=', company_id)]",
    )
    advance_recovery_type = fields.Selection(
        [('percent', 'Percentage of work done'), ('fixed', 'Fixed amount')],
        string='Advance Recovery By', default='percent',
    )
    advance_recovery_percent = fields.Float(string='Advance Recovery %', digits=(5, 2))
    advance_recovery_fixed = fields.Monetary(
        string='Advance Recovery (fixed)', currency_field='currency_id')

    # ------------------------------------------------------------------
    # Results shown on the invoice
    # ------------------------------------------------------------------
    retention_amount = fields.Monetary(
        string='Retention', compute='_compute_ra_amounts', store=True,
        currency_field='currency_id')
    advance_recovery_amount = fields.Monetary(
        string='Advance Recovery', compute='_compute_ra_amounts', store=True,
        currency_field='currency_id')
    amount_to_pay_now = fields.Monetary(
        string='Amount to Pay Now', compute='_compute_ra_amounts', store=True,
        currency_field='currency_id')
    ra_sale_order_id = fields.Many2one(
        'sale.order', string='Project', compute='_compute_ra_sale_order_id',
        store=True, index=True)
    retention_held = fields.Monetary(
        string='Retention Held', compute='_compute_ra_retention', currency_field='currency_id')
    retention_released = fields.Monetary(
        string='Retention Released', compute='_compute_ra_retention', currency_field='currency_id')
    retention_balance = fields.Monetary(
        string='Retention Balance', compute='_compute_ra_retention', currency_field='currency_id')

    # ------------------------------------------------------------------
    # Technical fields on the entries generated by this module
    # ------------------------------------------------------------------
    ra_type = fields.Selection(RA_TYPES, string='Retention/Advance Entry', copy=False, index=True)
    ra_source_id = fields.Many2one(
        'account.move', string='Created By', copy=False, index=True,
        help="Invoice or credit note whose posting created this entry.")
    ra_invoice_id = fields.Many2one(
        'account.move', string='Related Invoice', copy=False, index=True,
        help="Invoice whose retention or advance is moved by this entry.")
    ra_amount = fields.Monetary(
        string='Amount (company currency)', currency_field='company_currency_id',
        copy=False, readonly=True)
    ra_amount_currency = fields.Monetary(
        string='Amount', currency_field='ra_currency_id', copy=False, readonly=True)
    ra_currency_id = fields.Many2one(related='ra_invoice_id.currency_id', string='RA Currency')
    ra_entry_ids = fields.One2many('account.move', 'ra_source_id', string='Generated Entries')
    ra_linked_entry_ids = fields.One2many(
        'account.move', 'ra_invoice_id', string='Retention and Advance Entries')

    # ------------------------------------------------------------------
    # Defaults and constraints
    # ------------------------------------------------------------------
    @api.model
    def default_get(self, fields_list):
        values = super().default_get(fields_list)
        if ('retention_percent' in fields_list
                and self.env.context.get('default_move_type') == 'out_invoice'
                and 'default_retention_percent' not in self.env.context):
            values['retention_percent'] = self.env.company.ra_default_retention_percent
        return values

    @api.constrains('retention_percent', 'advance_recovery_percent')
    def _check_ra_percent(self):
        for move in self:
            for value in (move.retention_percent, move.advance_recovery_percent):
                if value < 0.0 or value > 100.0:
                    raise ValidationError(_("Percentages must be between 0 and 100."))

    # ------------------------------------------------------------------
    # Computes
    # ------------------------------------------------------------------
    @api.depends(
        'move_type', 'amount_untaxed', 'amount_total', 'retention_percent',
        'advance_recovery_type', 'advance_recovery_percent', 'advance_recovery_fixed',
        'reversed_entry_id.retention_amount', 'reversed_entry_id.advance_recovery_amount',
        'reversed_entry_id.amount_untaxed')
    def _compute_ra_amounts(self):
        for move in self:
            currency = move.currency_id or move.company_id.currency_id
            retention = advance = 0.0
            if move.move_type == 'out_invoice':
                # Retention and recovery are taken on the work done (amount without VAT).
                retention = currency.round(move.amount_untaxed * move.retention_percent / 100.0)
                if move.advance_recovery_type == 'fixed':
                    advance = move.advance_recovery_fixed
                else:
                    advance = currency.round(
                        move.amount_untaxed * move.advance_recovery_percent / 100.0)
            elif move.move_type == 'out_refund' and move.reversed_entry_id:
                origin = move.reversed_entry_id
                ratio = 0.0
                if origin.amount_untaxed:
                    ratio = min(move.amount_untaxed / origin.amount_untaxed, 1.0)
                retention = currency.round(origin.retention_amount * ratio)
                advance = currency.round(origin.advance_recovery_amount * ratio)
            move.retention_amount = retention
            move.advance_recovery_amount = advance
            if move.move_type in ('out_invoice', 'out_refund'):
                move.amount_to_pay_now = move.amount_total - retention - advance
            else:
                move.amount_to_pay_now = move.amount_total

    @api.depends(
        'invoice_line_ids.sale_line_ids.order_id',
        'ra_invoice_id.ra_sale_order_id',
        'reversed_entry_id.ra_sale_order_id')
    def _compute_ra_sale_order_id(self):
        for move in self:
            if move.ra_invoice_id:
                order = move.ra_invoice_id.ra_sale_order_id
            elif move.reversed_entry_id and move.move_type == 'out_refund':
                order = move.reversed_entry_id.ra_sale_order_id
            else:
                order = move.invoice_line_ids.sale_line_ids.order_id[:1]
            move.ra_sale_order_id = order

    def _compute_ra_retention(self):
        invoices = self.filtered(lambda m: isinstance(m.id, int) and m.move_type == 'out_invoice')
        totals = invoices._ra_type_totals()
        for move in self:
            data = totals.get(move.id, {}) if move in invoices else {}
            held = data.get('transfer', 0.0) - data.get('return', 0.0)
            released = data.get('release', 0.0)
            move.retention_held = held
            move.retention_released = released
            move.retention_balance = held - released

    # ------------------------------------------------------------------
    # Helpers
    # ------------------------------------------------------------------
    def _ra_type_totals(self):
        """{invoice id: {ra_type: amount in the invoice currency}} from posted entries.

        Reversal entries carry the negative amount, so they cancel the original.
        """
        result = defaultdict(lambda: defaultdict(float))
        ids = [i for i in self.ids if isinstance(i, int)]
        if not ids:
            return result
        groups = self.env['account.move']._read_group(
            [('ra_invoice_id', 'in', ids), ('state', '=', 'posted')],
            ['ra_invoice_id', 'ra_type'],
            ['ra_amount_currency:sum'],
        )
        for invoice, ra_type, amount in groups:
            result[invoice.id][ra_type] += amount
        return result

    def _ra_receivable_lines(self):
        return self.line_ids.filtered(lambda l: l.account_id.account_type == 'asset_receivable')

    def _ra_open_receivable_lines(self):
        return self._ra_receivable_lines().filtered(lambda l: not l.reconciled)

    def _ra_company_amount(self, amount):
        """Convert an amount of this invoice to company currency at the invoice rate."""
        self.ensure_one()
        company_currency = self.company_id.currency_id
        if self.currency_id == company_currency:
            return amount
        if self.amount_total:
            return company_currency.round(amount * abs(self.amount_total_signed) / self.amount_total)
        return company_currency._convert(
            amount, company_currency, self.company_id,
            self.date or fields.Date.context_today(self))

    def _ra_active_entries(self, ra_type=None):
        """Entries created by the posting of this document and not reversed yet."""
        self.ensure_one()
        entries = self.ra_entry_ids
        if ra_type:
            entries = entries.filtered(lambda e: e.ra_type == ra_type)
        if not entries:
            return entries
        reversed_ids = set(self.env['account.move'].search(
            [('reversed_entry_id', 'in', entries.ids)]).mapped('reversed_entry_id').ids)
        return entries.filtered(lambda e: e.id not in reversed_ids and e.state == 'posted')

    def _ra_line(self, account, amount, name, debit=True, partner=None, date_maturity=False):
        """Values of one journal item, in the currency of this invoice."""
        self.ensure_one()
        balance = self._ra_company_amount(amount)
        partner = partner or self.commercial_partner_id
        return {
            'account_id': account.id,
            'partner_id': partner.id,
            'name': name,
            'debit': balance if debit else 0.0,
            'credit': 0.0 if debit else balance,
            'amount_currency': amount if debit else -amount,
            'currency_id': self.currency_id.id,
            'date_maturity': date_maturity or False,
        }

    def _ra_make_entry(self, ra_type, date, lines, amount, label, source=None):
        """Create and post one journal entry. `self` is the invoice the entry belongs to."""
        self.ensure_one()
        company = self.company_id
        journal = company.ra_journal_id or self.env['account.journal'].search(
            [('type', '=', 'general'), ('company_id', '=', company.id)], limit=1)
        if not journal:
            raise UserError(_("No miscellaneous journal found for company %s.", company.name))
        entry = self.env['account.move'].with_company(company).create({
            'move_type': 'entry',
            'journal_id': journal.id,
            'company_id': company.id,
            'date': date,
            'ref': label,
            'partner_id': self.commercial_partner_id.id,
            'ra_type': ra_type,
            'ra_invoice_id': self.id,
            'ra_source_id': source.id if source else False,
            'ra_amount': self._ra_company_amount(amount),
            'ra_amount_currency': amount,
            'line_ids': [Command.create(vals) for vals in lines],
        })
        entry._post(soft=False)
        return entry

    # ------------------------------------------------------------------
    # Posting
    # ------------------------------------------------------------------
    def _post(self, soft=True):
        self.filtered(
            lambda m: m.move_type == 'out_invoice' and m.state == 'draft'
        )._ra_validate_before_post()
        posted = super()._post(soft=soft)
        posted._ra_process_posted()
        return posted

    def _ra_validate_before_post(self):
        used_company = defaultdict(float)
        for move in self:
            retention, advance = move.retention_amount, move.advance_recovery_amount
            if not (retention or advance):
                continue
            currency = move.currency_id
            if currency.compare_amounts(retention + advance, move.amount_total) > 0:
                raise UserError(_(
                    "Retention plus advance recovery cannot be more than the invoice total."))
            if retention:
                account = move.company_id.ra_retention_account_id
                if not account:
                    raise UserError(_(
                        "Please choose the Retention Receivable account in the Accounting "
                        "settings of company %s.", move.company_id.name))
                if not move.retention_due_date:
                    raise UserError(_("Please enter the expected handover date for the retention."))
            if advance:
                payment = move.advance_payment_id
                if not payment:
                    raise UserError(_("Please select the advance payment to recover from."))
                if payment.partner_id.commercial_partner_id != move.commercial_partner_id:
                    raise UserError(_("The advance payment belongs to another customer."))
                available = payment._ra_available_in(
                    currency, move.date or fields.Date.context_today(move))
                if currency.compare_amounts(advance, available) > 0:
                    raise UserError(_(
                        "Advance recovery %(amount)s is more than what is left on the advance "
                        "payment %(payment)s (%(left)s).",
                        amount=advance, payment=payment.display_name, left=available))
                used_company[payment] += move._ra_company_amount(advance)
        for payment, used in used_company.items():
            company_currency = payment.company_id.currency_id
            if company_currency.compare_amounts(used, payment._ra_available_company()) > 0:
                raise UserError(_(
                    "The invoices you are posting recover more than what is left on the "
                    "advance payment %s.", payment.display_name))

    def _ra_process_posted(self):
        for move in self.filtered(
                lambda m: m.state == 'posted' and m.move_type in ('out_invoice', 'out_refund')):
            if move.move_type == 'out_invoice':
                move._ra_process_invoice()
            else:
                move._ra_process_refund()

    def _ra_process_invoice(self):
        self.ensure_one()
        # Nothing is duplicated: an entry is only created if no live one exists.
        if self.retention_amount and not self._ra_active_entries('transfer'):
            self._ra_create_transfer()
        if self.advance_recovery_amount and not self._ra_active_entries('advance_apply'):
            self._ra_create_advance_application()

    def _ra_create_transfer(self):
        """Dr Retention Receivable / Cr Receivable, then match the credit with the invoice."""
        self.ensure_one()
        retention_account = self.company_id.ra_retention_account_id
        receivable = self._ra_receivable_lines()[:1]
        if retention_account == receivable.account_id:
            raise UserError(_(
                "The Retention Receivable account must be different from the receivable account."))
        amount = self.retention_amount
        label = _("Retention held - %s", self.name)
        partner = receivable.partner_id
        entry = self._ra_make_entry('transfer', self.date, [
            self._ra_line(retention_account, amount, label, debit=True, partner=partner,
                          date_maturity=self.retention_due_date),
            self._ra_line(receivable.account_id, amount, label, debit=False, partner=partner),
        ], amount=amount, label=label, source=self)
        credit_line = entry.line_ids.filtered(lambda l: l.credit)
        (credit_line | self._ra_open_receivable_lines()).reconcile()

    def _ra_create_advance_application(self):
        """Use part of the advance payment to pay this invoice.

        The payment credit cannot be split, so a small entry is used as a bridge:
        Dr (matched with the payment) / Cr (matched with the invoice).
        """
        self.ensure_one()
        payment = self.advance_payment_id
        pay_lines = payment._ra_open_credit_lines()
        if not pay_lines:
            raise UserError(_("Nothing is left on the advance payment %s.", payment.display_name))
        pay_line = pay_lines[0]
        receivable = self._ra_receivable_lines()[:1]
        amount = self.advance_recovery_amount
        label = _("Advance recovery - %s", self.name)
        entry = self._ra_make_entry('advance_apply', self.date, [
            self._ra_line(receivable.account_id, amount, label, debit=False,
                          partner=receivable.partner_id),
            self._ra_line(pay_line.account_id, amount, label, debit=True,
                          partner=pay_line.partner_id),
        ], amount=amount, label=label, source=self)
        credit_line = entry.line_ids.filtered(lambda l: l.credit)
        debit_line = entry.line_ids.filtered(lambda l: l.debit)
        (debit_line | pay_line).reconcile()
        (credit_line | self._ra_open_receivable_lines()).reconcile()
        # The advance belongs to the project of the first invoice that uses it.
        vals = {'ra_is_advance': True}
        if not payment.ra_sale_order_id and self.ra_sale_order_id:
            vals['ra_sale_order_id'] = self.ra_sale_order_id.id
        payment.write(vals)

    # ------------------------------------------------------------------
    # Credit notes
    # ------------------------------------------------------------------
    def _ra_capped_refund_amounts(self):
        """Retention and advance to give back, never more than what is still there."""
        self.ensure_one()
        origin = self.reversed_entry_id
        data = origin._ra_type_totals()[origin.id]
        currency = origin.currency_id
        retention_left = max(data['transfer'] - data['return'] - data['release'], 0.0)
        advance_left = max(data['advance_apply'] - data['advance_return'], 0.0)
        retention = min(self.retention_amount, currency.round(retention_left))
        advance = min(self.advance_recovery_amount, currency.round(advance_left))
        return retention, advance

    def _ra_process_refund(self):
        self.ensure_one()
        origin = self.reversed_entry_id
        if (not origin or origin.move_type != 'out_invoice' or origin.state != 'posted'
                or self._ra_active_entries()):
            return
        retention, advance = self._ra_capped_refund_amounts()
        if not (retention or advance):
            return
        receivable = self._ra_open_receivable_lines()
        if not receivable:
            return
        partner = receivable[:1].partner_id
        account = receivable[:1].account_id
        to_match = self.env['account.move.line']
        if retention:
            label = _("Retention returned - %s", self.name)
            entry = origin._ra_make_entry('return', self.date, [
                origin._ra_line(account, retention, label, debit=True, partner=partner),
                origin._ra_line(origin.company_id.ra_retention_account_id, retention, label,
                                debit=False, partner=partner),
            ], amount=retention, label=label, source=self)
            to_match |= entry.line_ids.filtered(lambda l: l.debit)
        if advance:
            # Dr is matched with the credit note, Cr stays open: the advance is given back
            # to the customer as a free credit.
            label = _("Advance returned - %s", self.name)
            entry = origin._ra_make_entry('advance_return', self.date, [
                origin._ra_line(account, advance, label, debit=True, partner=partner),
                origin._ra_line(account, advance, label, debit=False, partner=partner),
            ], amount=advance, label=label, source=self)
            to_match |= entry.line_ids.filtered(lambda l: l.debit)
        (to_match | receivable).reconcile()
        # What is left of the credit note pays the invoice (the amount to pay now).
        rest = self._ra_open_receivable_lines()
        open_origin = origin._ra_open_receivable_lines()
        if rest and open_origin:
            (rest | open_origin).reconcile()

    # ------------------------------------------------------------------
    # Reset to draft
    # ------------------------------------------------------------------
    def button_draft(self):
        documents = self.filtered(
            lambda m: m.move_type in ('out_invoice', 'out_refund')
            and m.state == 'posted' and m.ra_entry_ids)
        documents._ra_check_can_reset()
        res = super().button_draft()
        documents._ra_reverse_entries()
        return res

    def _ra_check_can_reset(self):
        for move in self.filtered(lambda m: m.move_type == 'out_invoice'):
            data = move._ra_type_totals()[move.id]
            if data['release'] or data['return'] or data['advance_return']:
                raise UserError(_(
                    "%s cannot be reset to draft because its retention was already released "
                    "or credited.", move.name))

    def _ra_reverse_entries(self):
        """Reverse (never delete) the live entries of the documents reset to draft."""
        today = fields.Date.context_today(self)
        for move in self:
            for entry in move._ra_active_entries():
                entry.line_ids.remove_move_reconcile()
                entry._reverse_moves([{
                    'date': today,
                    'ref': _("Reversal of %s", entry.name),
                    'ra_type': entry.ra_type,
                    'ra_invoice_id': entry.ra_invoice_id.id,
                    'ra_source_id': False,
                    'ra_amount': -entry.ra_amount,
                    'ra_amount_currency': -entry.ra_amount_currency,
                }], cancel=True)
